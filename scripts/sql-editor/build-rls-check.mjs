// Builds scripts/sql-editor/rls_check.sql from supabase/tests/database/rls.test.sql.
// `supabase test db` needs Docker; this produces a copy that runs in the Dashboard SQL Editor.
// Each pgTAP result is appended to a transaction-local setting (works under any role), and a
// final RAISE EXCEPTION prints them — which also guarantees the transaction never commits.
// Run: npm run db:test:editor   (then paste scripts/sql-editor/rls_check.sql into the SQL Editor)
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('supabase/tests/database/rls.test.sql', 'utf8').replace(/\r\n/g, '\n');
const begin = src.indexOf('begin;\n');
const end = src.lastIndexOf('select * from finish();');
if (begin < 0 || end < 0)
  throw new Error('rls.test.sql must contain "begin;" and "select * from finish();"');

const body = src
  .slice(begin + 'begin;\n'.length, end)
  .replace(/^select ([\s\S]*?);$/gm, (stmt, expr) =>
    expr.startsWith('set_config(')
      ? stmt
      : `select set_config('vz.tap', current_setting('vz.tap') || E'\\n' || ${expr}, true);`,
  );

const header = `-- GENERATED by scripts/sql-editor/build-rls-check.mjs from supabase/tests/database/rls.test.sql.
-- Do not edit by hand: change rls.test.sql, then run \`npm run db:test:editor\`.
-- How to run: Dashboard -> SQL Editor -> paste this whole file -> Run.
-- It ALWAYS ends with an error named "RLS TEST RESULTS": that error carries the results and
-- aborts the transaction, so none of the test fixtures below are ever saved.
-- Pass = every line starts with "ok" and there is no "Looks like you failed" line.
begin;
select set_config('vz.tap', '', true);
`;

const footer = `reset role;
do $$
begin
  raise exception E'RLS TEST RESULTS (rolled back, nothing saved)\\n%',
    current_setting('vz.tap')
    || coalesce(E'\\n' || (select string_agg(f, E'\\n') from finish() f), '');
end $$;
rollback;
`;

writeFileSync('scripts/sql-editor/rls_check.sql', header + body.replace(/^\n+/, '') + footer);
process.stdout.write('Wrote scripts/sql-editor/rls_check.sql\n');
